import type { ReactNode } from "react";

// Inline SVG icons. They replaced the Bootstrap Icons and Boxicons fonts, which made every page
// load 231 KB of font files and two stylesheets of a few thousand rules, for about 25 glyphs.
// The shapes are the same ones, both MIT licensed: Bootstrap Icons 1.10.5's SVG files, and the
// glyphs of the Boxicons font this site used to ship (public/assets/vendor/boxicons). Like the
// font icons, each is 1em square in the current colour, so font-size and text colour classes
// still size and colour them. To add one, take its SVG path from the same icon set.

type IconProps = Readonly<{ className?: string }>;

// Where the fonts sat on the line: Bootstrap Icons set vertical-align: -0.125em, and a Boxicons
// glyph's baseline is 64/1024 em above the bottom of its box.
const ALIGN = { bi: "align-[-0.125em]", bx: "align-[-0.0625em]" } as const;

function Icon({
  name,
  set,
  viewBox,
  className = "",
  children,
}: Readonly<{
  name: string;
  set: keyof typeof ALIGN;
  viewBox: string;
  className?: string;
  children: ReactNode;
}>) {
  // A caller's own align-* class wins over the font's default.
  const align = /(^|\s)align-/.test(className) ? "" : ALIGN[set];
  return (
    <svg
      viewBox={viewBox}
      width="1em"
      height="1em"
      fill="currentColor"
      aria-hidden="true"
      focusable="false"
      data-icon={name}
      className={`inline-block shrink-0 ${align} ${className}`.trim()}
    >
      {children}
    </svg>
  );
}

